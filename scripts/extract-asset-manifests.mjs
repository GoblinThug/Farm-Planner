import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const appJs = fs.existsSync(path.join(root, 'App.js'))
  ? fs.readFileSync(path.join(root, 'App.js'), 'utf8')
  : '';

const bundleItemIconsPath = path.join(root, 'data/bundle-item-icons.json');
const bundleManifestPath = path.join(root, 'data/bundle-image-manifest.json');

const existingBundleItems = fs.existsSync(bundleItemIconsPath)
  ? JSON.parse(fs.readFileSync(bundleItemIconsPath, 'utf8'))
  : {};
const existingBundleManifest = fs.existsSync(bundleManifestPath)
  ? JSON.parse(fs.readFileSync(bundleManifestPath, 'utf8'))
  : { bundleIcons: {}, roomIcons: {} };

const requireRe = /require\(['"](\.\/assets\/[^'"]+)['"]\)/g;
const namedRequireRe = /"([^"]+)":\s*require\(['"](\.\/assets\/[^'"]+)['"]\)/g;

const bundleItemIconsFromApp = {};
let m;
while ((m = namedRequireRe.exec(appJs)) !== null) {
  const [, name, rel] = m;
  if (!rel.includes('/bundles/')) {
    bundleItemIconsFromApp[name] = rel.replace(/^\.\/assets\//, 'assets/');
  }
}

const bundleImageAssets = { ...existingBundleManifest.bundleIcons };
const bundleRoomImages = { ...existingBundleManifest.roomIcons };

if (appJs.includes('const bundleImageAssets')) {
  const bundleBlock = appJs.slice(appJs.indexOf('const bundleImageAssets'), appJs.indexOf('const bundleNavIcon'));
  for (const line of bundleBlock.split('\n')) {
    const match = line.match(/^\s+'([^']+)':\s*require\('\.\/assets\/([^']+)'\)/);
    if (match) bundleImageAssets[match[1]] = `assets/${match[2]}`;
  }
}
if (appJs.includes('const bundleRoomImages')) {
  const roomBlock = appJs.slice(appJs.indexOf('const bundleRoomImages'), appJs.indexOf('const bundleNavIcon'));
  for (const line of roomBlock.split('\n')) {
    const match = line.match(/^\s+'([^']+)':\s*require\('\.\/assets\/([^']+)'\)/);
    if (match) bundleRoomImages[match[1]] = `assets/${match[2]}`;
  }
}

const normalizeAssetPath = (file) => {
  if (!file) return file;
  return file.replace(/\.png\.png$/i, '.png');
};

const mergedBundleItems = { ...existingBundleItems };
for (const [name, file] of Object.entries(bundleItemIconsFromApp)) {
  mergedBundleItems[name] = normalizeAssetPath(file);
}
for (const name of Object.keys(mergedBundleItems)) {
  mergedBundleItems[name] = normalizeAssetPath(mergedBundleItems[name]);
}

const cropImages = JSON.parse(fs.readFileSync(path.join(root, 'data/crop-images.json'), 'utf8'));
const fishImages = JSON.parse(fs.readFileSync(path.join(root, 'data/fish-images.json'), 'utf8'));
const animalImages = fs.existsSync(path.join(root, 'data/animal-images.json'))
  ? JSON.parse(fs.readFileSync(path.join(root, 'data/animal-images.json'), 'utf8'))
  : {};
const animalProductImages = fs.existsSync(path.join(root, 'data/animal-product-images.json'))
  ? JSON.parse(fs.readFileSync(path.join(root, 'data/animal-product-images.json'), 'utf8'))
  : {};

const allPaths = new Set();
const addPath = (p) => {
  if (p) allPaths.add(p.replace(/^\.\/assets\//, 'assets/').replace(/^assets\//, 'assets/'));
};

Object.values(cropImages).forEach((v) => addPath(v.file));
Object.values(fishImages).forEach((v) => addPath(v.file));
Object.values(animalImages).forEach((v) => addPath(v.file));
Object.values(animalProductImages).forEach((v) => addPath(v.file));
Object.values(bundleImageAssets).forEach(addPath);
Object.values(bundleRoomImages).forEach(addPath);
Object.values(mergedBundleItems).forEach(addPath);
while ((m = requireRe.exec(appJs)) !== null) addPath(m[1]);

const uiPaths = [
  'assets/ui/calendar.png',
  'assets/ui/crops.png',
  'assets/ui/fish.png',
  'assets/ui/animals.png',
  'assets/ui/plus.png',
  'assets/ui/close.png',
  'assets/ui/bundle.png',
  'assets/ui/winter.png',
  'assets/profile/farmer.png',
];
uiPaths.forEach(addPath);
['assets/crops/tulip.png', 'assets/crops/sunflower.png', 'assets/crops/pumpkin.png'].forEach(addPath);

fs.writeFileSync(
  bundleManifestPath,
  JSON.stringify({ bundleIcons: bundleImageAssets, roomIcons: bundleRoomImages }, null, 2) + '\n'
);
fs.writeFileSync(bundleItemIconsPath, JSON.stringify(mergedBundleItems, null, 2) + '\n');

const sortedPaths = [...allPaths].sort();
const registryLines = sortedPaths.map((p) => {
  const key = p.replace(/^assets\//, '').replace(/\\/g, '/');
  const requirePath = `../../assets/${key}`;
  return `  ${JSON.stringify(key)}: require(${JSON.stringify(requirePath)}),`;
});

const registry = `// Auto-generated by scripts/extract-asset-manifests.mjs — do not edit by hand.
// Re-run: npm run sync:assets

const assetsByPath = {
${registryLines.join('\n')}
};

export function resolveAssetPath(filePath) {
  if (!filePath) return undefined;
  const normalized = String(filePath).replace(/^\\.\\//, '').replace(/^assets\\//, '');
  return assetsByPath[normalized];
}

export function mapManifestToSprites(manifest) {
  const out = {};
  for (const [name, entry] of Object.entries(manifest)) {
    const file = typeof entry === 'string' ? entry : entry?.file;
    const source = resolveAssetPath(file);
    if (source) out[name] = source;
  }
  return out;
}

export default assetsByPath;
`;

fs.writeFileSync(path.join(root, 'src/assets/assetRegistry.js'), registry);

console.log('bundle icons:', Object.keys(bundleImageAssets).length);
console.log('bundle rooms:', Object.keys(bundleRoomImages).length);
console.log('bundle items:', Object.keys(mergedBundleItems).length);
console.log('unique asset paths:', sortedPaths.length);
console.log('Wrote data/bundle-image-manifest.json, data/bundle-item-icons.json, src/assets/assetRegistry.js');